/** Canonical 16-entry Spectrum palette (index 0-7 normal, 8-15 bright), as RGB
 * triples. The core's framebuffer stays palette-indexed (see ulaEngine.ts) — this
 * table is exported so the app's blit-time RGBA expansion LUT and the core's own
 * tests share one source of truth instead of duplicating the constants. */
export const SPECTRUM_PALETTE_RGB: readonly (readonly [number, number, number])[] = [
  [0x00, 0x00, 0x00],
  [0x00, 0x00, 0xd7],
  [0xd7, 0x00, 0x00],
  [0xd7, 0x00, 0xd7],
  [0x00, 0xd7, 0x00],
  [0x00, 0xd7, 0xd7],
  [0xd7, 0xd7, 0x00],
  [0xd7, 0xd7, 0xd7],
  [0x00, 0x00, 0x00],
  [0x00, 0x00, 0xff],
  [0xff, 0x00, 0x00],
  [0xff, 0x00, 0xff],
  [0x00, 0xff, 0x00],
  [0x00, 0xff, 0xff],
  [0xff, 0xff, 0x00],
  [0xff, 0xff, 0xff],
];

export function paletteIndex(color3bit: number, bright: boolean): number {
  return (color3bit & 0x07) | (bright ? 0x08 : 0);
}
